import assert from 'node:assert/strict';
import { build } from 'esbuild';

const queue = new Map();
let frameId = 0;
let wallTime = 0;
Object.defineProperty(globalThis, 'performance', { value: { now: () => wallTime }, configurable: true });
globalThis.requestAnimationFrame = callback => { queue.set(++frameId, callback); return frameId; };
globalThis.cancelAnimationFrame = id => queue.delete(id);
const result = await build({ entryPoints: ['src/simulation-runtime/SimulationRuntime.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { SimulationRuntime } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const runtime = new SimulationRuntime();
let frame;
let ended = 0;
runtime.subscribe(value => { frame = value; });
runtime.subscribePlaybackEnd(() => ended++);
const simulation = { time: [0, 0.05, 0.1, 0.3], positions: { x: [0, 1, 2, 6] }, velocities: {}, accelerations: {}, values: {} };
runtime.setSimulation(simulation);
assert.equal(frame.data.time[1], simulation.time[1], 'solver timestamps must be preserved exactly');
runtime.seek(0.05);
assert.equal(runtime.getIndex(), 1, 'exact sample time must select its sample');
runtime.setSpeed(2);
runtime.play();
runtime.play();
assert.equal(queue.size, 1, 'repeated Play must not create another clock');
wallTime = 50;
const tick = [...queue.values()][0]; queue.clear(); tick(wallTime);
assert.ok(Math.abs(runtime.getTime() - 0.15) < 1e-12, '2x speed advances 0.1 simulation seconds in 50 ms');
runtime.pause();
assert.equal(queue.size, 0);
runtime.seek(-1); assert.equal(runtime.getTime(), 0);
runtime.seek(100); assert.equal(runtime.getTime(), 0.3);
runtime.play(); assert.equal(runtime.getTime(), 0, 'Play at the end restarts');
wallTime = 250;
const endTick = [...queue.values()][0]; queue.clear(); endTick(wallTime);
assert.equal(runtime.getTime(), 0.3);
assert.equal(ended, 1);
assert.equal(runtime.isPlaying(), false);
runtime.setSimulation({ ...simulation, time: [5, 5.1, 6] });
assert.equal(runtime.getTime(), 5, 'switching simulations resets to its first solver timestamp');
runtime.destroy(); assert.equal(queue.size, 0);
console.log('PASS: timestamp precision, seek, speed, pause, restart, end and simulation swap.');
