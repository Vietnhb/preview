-- Repair a legacy database whose Flyway history advanced while the
-- Hibernate-owned application tables were not present.  This migration is
-- additive and idempotent: existing tables and rows are preserved, and only
-- missing relations are created.  Foreign keys are added NOT VALID so legacy
-- orphan rows cannot make startup destructive; new writes are still checked.

CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS evaluation_runs (
    benchmark_count INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    id UUID NOT NULL,
